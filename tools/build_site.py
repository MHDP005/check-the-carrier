#!/usr/bin/env python3
"""Apply the shared site chrome and generated blocks to every page, then rebuild the sitemap.

    python3 tools/build_site.py          # rewrite pages + sitemap.xml
    python3 tools/build_site.py --check  # only validate, change nothing

What it does, for every *.html page outside tools/, assets/ and screenshots/:
  * replaces the block between <!-- SITE HEADER --> and <!-- /SITE HEADER -->
    with the shared header and nav (built from tools/site.json);
  * replaces the block between <!-- SITE FOOTER --> and <!-- /SITE FOOTER -->
    with the shared footer, keeping the page's own <div class="disclosure"> text;
  * fills any <!-- GENERATED:name --> ... <!-- /GENERATED:name --> block
    (area-cards, area-options, area-links, guide-cards, photo-credits);
  * validates JSON-LD, canonical URLs, local links/images and the
    AFFILIATE CTA SLOT comments, and fails loudly if something is wrong;
  * regenerates sitemap.xml via tools/build_sitemap.py.

To add a page: copy tools/templates/area-page.html or guide-page.html, add an
entry to "areas" or "guides" in tools/site.json, then run this script.
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_DIRS = {".git", "tools", "screenshots", "assets", "node_modules"}
SITE = json.loads((ROOT / "tools" / "site.json").read_text(encoding="utf-8"))
FONT_LINK = '<link href="https://fonts.googleapis.com/css2?family=Nunito:wght@400;600;700;800&display=swap" rel="stylesheet">'
DEFAULT_DISCLOSURE = """
        <p>This site is not affiliated with the Environment Agency, Defra, any council or any waste company. Listings are a starting point, not a recommendation or guarantee. Always check a carrier yourself on the official register before you hire them. Registrations can expire or change.</p>
        <p><strong>Affiliate disclosure.</strong> Some links on this site may in future be affiliate or referral links. If that happens and we earn a commission, it should not change the price you pay. We will mark those links clearly. There are no live affiliate links on this version of the site.</p>
      """

BRAND_SVG = """<svg class="brand-mark" viewBox="0 0 64 64" aria-hidden="true" focusable="false">
  <rect width="64" height="64" rx="16" fill="#17694b"/>
  <path d="M12 26h40l-5 22H17z" fill="#f5b82e"/>
  <path d="M22 35l7 7 13-14" fill="none" stroke="#0f4a35" stroke-width="5.5" stroke-linecap="round" stroke-linejoin="round"/>
</svg>"""


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def icon(name: str, prefix: str, cls: str = "icon") -> str:
    return f'<svg class="{cls}" aria-hidden="true" focusable="false"><use href="{prefix}assets/icons.svg#{name}"/></svg>'


def picture(slug: str | None, prefix: str, sizes: str, eager: bool = False, cls: str = "") -> str:
    """<picture> markup for an image in tools/site.json "images" (WebP srcset + JPEG fallback)."""
    if not slug:
        return ""
    im = SITE["images"][slug]
    widths = im["widths"]
    small = widths[0]
    rw, rh = (int(x) for x in im.get("ratio", "3:2").split(":"))
    srcset = ", ".join(f"{prefix}assets/img/{slug}-{w}.webp {w}w" for w in widths)
    load = 'fetchpriority="high"' if eager else 'loading="lazy"'
    h = round(small * rh / rw)
    c = f' class="{cls}"' if cls else ""
    return (f'<picture{c}><source type="image/webp" srcset="{srcset}" sizes="{sizes}">'
            f'<img src="{prefix}assets/img/{slug}-{small}.jpg" width="{small}" height="{h}" alt="{esc(im["alt"])}" {load} decoding="async"></picture>')


def credit(slug: str, prefix: str) -> str:
    im = SITE["images"][slug]
    return (f'Photo: <a href="{esc(im["source_url"])}">{esc(im["author"])}</a>, '
            f'<a href="{esc(im["licence_url"])}">{esc(im["licence"])}</a>, via {esc(im["source_name"])} ({esc(im["changes"])}). '
            f'<a href="{prefix}credits.html">All photo credits</a>')


def header(prefix: str, current: str) -> str:
    def link(path: str, label: str, cls: str = "") -> str:
        cur = ' aria-current="page"' if path == current else ""
        c = f' class="{cls}"' if cls else ""
        return f'<a{c} href="{prefix}{path}"{cur}>{esc(label)}</a>'
    areas = "\n".join(f"              <li>{link(a['path'], a['name'])}</li>" for a in SITE["areas"])
    guides = "\n".join(f"              <li>{link(g['path'], g['name'])}</li>" for g in SITE["guides"] if g["path"] != "guides/check-a-waste-carrier.html")
    return f"""<!-- SITE HEADER: generated by tools/build_site.py from tools/site.json. Do not edit by hand. -->
  <header class="site-header">
    <div class="wrap header-inner">
      <a class="brand" href="{prefix}index.html">
        {BRAND_SVG}
        <span class="brand-text">
          <strong>{esc(SITE['site_name'])}</strong>
          <span>Licensed skip &amp; rubbish removal</span>
        </span>
      </a>
      <button class="nav-toggle" type="button" aria-expanded="false" aria-controls="site-nav">{icon('i-list', prefix)} Menu</button>
      <nav class="site-nav" id="site-nav" aria-label="Main">
        <ul class="nav-list">
          <li>{link('index.html', 'Home')}</li>
          <li>
            <details class="nav-group">
              <summary>Find a firm</summary>
              <ul>
{areas}
              </ul>
            </details>
          </li>
          <li>
            <details class="nav-group">
              <summary>Guides</summary>
              <ul>
{guides}
              </ul>
            </details>
          </li>
          <li>{link('guides/check-a-waste-carrier.html', 'Check a licence', 'nav-cta')}</li>
        </ul>
      </nav>
    </div>
  </header>
  <!-- /SITE HEADER -->"""


def footer(prefix: str, disclosure: str) -> str:
    areas = "\n".join(f'            <li><a href="{prefix}{a["path"]}">Skip hire in {esc(a["card_title"])}</a></li>' for a in SITE["areas"])
    guides = "\n".join(f'            <li><a href="{prefix}{g["path"]}">{esc(g["card_title"])}</a></li>' for g in SITE["guides"])
    return f"""<!-- SITE FOOTER: generated by tools/build_site.py. Page-specific text lives in the disclosure div and is kept. -->
  <footer class="site-footer">
    <div class="wrap">
      <div class="footer-grid">
        <div class="footer-brand">
          {BRAND_SVG}
          <h2>{esc(SITE['site_name'])}</h2>
          <p>An independent, unofficial directory to help householders in England find licensed skip hire, skip bags and junk removal, and check a waste carrier before they hire one.</p>
        </div>
        <div>
          <h2>Find a firm</h2>
          <ul>
{areas}
          </ul>
        </div>
        <div>
          <h2>Guides</h2>
          <ul>
{guides}
          </ul>
        </div>
        <div>
          <h2>Official registers</h2>
          <ul>
            <li><a href="https://environment.data.gov.uk/public-register/view/search-waste-carriers-brokers">England: Environment Agency register</a></li>
            <li><a href="https://www.gov.uk/dispose-household-waste">Dispose of household waste (GOV.UK)</a></li>
            <li><a href="https://www.gov.uk/government/publications/waste-duty-of-care-code-of-practice/waste-duty-of-care-code-of-practice">Waste duty of care: code of practice</a></li>
            <li><a href="{prefix}credits.html">Photo credits</a></li>
          </ul>
        </div>
      </div>
      <div class="disclosure">{disclosure}</div>
    </div>
  </footer>
  <!-- /SITE FOOTER -->"""


def area_cards(prefix: str) -> str:
    out = []
    for a in SITE["areas"]:
        pic = picture(a.get("image"), prefix, "(min-width: 56rem) 22rem, (min-width: 36rem) 45vw, 92vw")
        photo = f'<div class="card-photo">{pic}</div>' if pic else f'<div class="card-photo card-photo-blank">{icon("i-pin", prefix)}</div>'
        out.append(f"""          <article class="card">
            {photo}
            <p class="card-meta">{icon('i-pin', prefix)} {esc(a.get('postcodes', ''))}</p>
            <h3>{esc(a['card_title'])}</h3>
            <p>{esc(a['blurb'])}</p>
            <a class="card-link" href="{prefix}{a['path']}">See licensed firms {icon('i-arrow', prefix)}</a>
          </article>""")
    return "\n" + "\n".join(out) + "\n          "


def guide_cards(prefix: str) -> str:
    out = []
    for g in SITE["guides"]:
        out.append(f"""          <article class="card">
            <span class="icon-bubble">{icon(g.get('icon', 'i-book'), prefix)}</span>
            <h3>{esc(g['card_title'])}</h3>
            <p>{esc(g['blurb'])}</p>
            <a class="card-link" href="{prefix}{g['path']}">Read the guide {icon('i-arrow', prefix)}</a>
          </article>""")
    return "\n" + "\n".join(out) + "\n          "


def area_options(prefix: str) -> str:
    opts = "\n".join(f'              <option value="{prefix}{a["path"]}">{esc(a["name"])} ({esc(a.get("postcodes", ""))})</option>' for a in SITE["areas"])
    return "\n" + opts + "\n              "


def area_links(prefix: str) -> str:
    return "\n" + "\n".join(f'            <li><a class="chip" href="{prefix}{a["path"]}">{esc(a["name"])}</a></li>' for a in SITE["areas"]) + "\n          "


def photo_credits(prefix: str) -> str:
    rows = []
    for slug, im in SITE["images"].items():
        rows.append(f"""            <li class="credit-item">{picture(slug, prefix, '8rem')}
              <div><strong>{esc(im['alt'])}</strong><br>
              By <a href="{esc(im['source_url'])}">{esc(im['author'])}</a>, licensed under <a href="{esc(im['licence_url'])}">{esc(im['licence'])}</a>, via {esc(im['source_name'])}. Changes: {esc(im['changes'])}.</div></li>""")
    return "\n" + "\n".join(rows) + "\n          "


GENERATORS = {
    "area-cards": area_cards,
    "guide-cards": guide_cards,
    "area-options": area_options,
    "area-links": area_links,
    "photo-credits": photo_credits,
}


def iter_pages() -> list[Path]:
    pages = []
    for p in ROOT.rglob("*.html"):
        rel = p.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        pages.append(rel)
    return sorted(pages)


def process(rel: Path, text: str) -> str:
    prefix = "../" * (len(rel.parts) - 1)
    current = rel.as_posix()
    # Disclosure (page-specific) from the existing footer
    m = re.search(r'<div class="disclosure">(.*?)</div>', text, re.S)
    disclosure = m.group(1) if m else DEFAULT_DISCLOSURE
    # Header
    hdr = header(prefix, current)
    if "<!-- SITE HEADER" in text:
        text = re.sub(r"<!-- SITE HEADER.*?<!-- /SITE HEADER -->", lambda _: hdr, text, count=1, flags=re.S)
    else:
        text = re.sub(r'<header class="site-header">.*?</header>', lambda _: hdr, text, count=1, flags=re.S)
    ftr = footer(prefix, disclosure)
    if "<!-- SITE FOOTER" in text:
        text = re.sub(r"<!-- SITE FOOTER.*?<!-- /SITE FOOTER -->", lambda _: ftr, text, count=1, flags=re.S)
    else:
        text = re.sub(r'<footer class="site-footer">.*?</footer>', lambda _: ftr, text, count=1, flags=re.S)
    # Generated blocks
    for name, fn in GENERATORS.items():
        text = re.sub(rf"(<!-- GENERATED:{name} -->)(.*?)(<!-- /GENERATED:{name} -->)",
                      lambda mm, fn=fn: mm.group(1) + fn(prefix) + mm.group(3), text, flags=re.S)
    # Fonts: one family, swap
    text = re.sub(r'<link href="https://fonts\.googleapis\.com/css2[^"]*" rel="stylesheet">', FONT_LINK, text)
    text = re.sub(r'<meta[^>]*name="theme-color"[^>]*>', '<meta name="theme-color" content="#17694b">', text)
    return text


def validate(rel: Path, text: str) -> list[str]:
    errs = []
    prefix_dir = (ROOT / rel).parent
    for block in re.findall(r'<script type="application/ld\+json">(.*?)</script>', text, re.S):
        try:
            json.loads(block)
        except json.JSONDecodeError as e:
            errs.append(f"{rel}: invalid JSON-LD ({e})")
    if 'rel="canonical"' not in text:
        errs.append(f"{rel}: missing canonical link")
    if rel.as_posix() != "credits.html" and "AFFILIATE CTA SLOT" not in text:
        errs.append(f"{rel}: no AFFILIATE CTA SLOT comment")
    if text.count("<main") != 1 or text.count("</main>") != 1:
        errs.append(f"{rel}: expected exactly one <main>")
    for attr in re.findall(r'(?:href|src)="([^"#:?]+)(?:#[^"]*)?"', text):
        if attr.startswith(("http", "mailto", "tel", "//")) or attr == "":
            continue
        if not (prefix_dir / attr).resolve().exists():
            errs.append(f"{rel}: broken local link {attr}")
    for s in re.findall(r'srcset="([^"]+)"', text):
        for part in s.split(","):
            url = part.strip().split(" ")[0]
            if not (prefix_dir / url).resolve().exists():
                errs.append(f"{rel}: missing image {url}")
    return errs


def main() -> int:
    check_only = "--check" in sys.argv
    errors = []
    for rel in iter_pages():
        path = ROOT / rel
        old = path.read_text(encoding="utf-8")
        new = old if check_only else process(rel, old)
        errors += validate(rel, new)
        if new != old:
            path.write_text(new, encoding="utf-8")
            print(f"updated {rel}", file=sys.stderr)
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if not check_only:
        sys.path.insert(0, str(ROOT / "tools"))
        import build_sitemap
        build_sitemap.main()
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
